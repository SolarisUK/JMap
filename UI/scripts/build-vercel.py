"""Prepare CDN files for Vercel without moving UI sources or touching the API.

Run from any directory: python -B UI/scripts/build-vercel.py
The generated root public/ directory belongs to this script and is gitignored.
"""
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[2]
UI = ROOT / 'UI'
PUBLIC = ROOT / 'public'
MARKER = '.jmap-build.json'


def build(output=PUBLIC):
    output = Path(output).absolute()
    # Only generated public/ directories inside this workspace can be replaced.
    if output.name != 'public' or not output.resolve().is_relative_to(ROOT) or output.is_symlink():
        raise ValueError('Build output must be a public/ directory inside the repository.')
    if output.exists():
        if not (output / MARKER).is_file() and any(output.iterdir()):
            raise ValueError('Refusing to replace a public/ directory not generated by JMap.')
        shutil.rmtree(output)
    output.mkdir(parents=True)
    sources = [p for p in UI.iterdir() if p.is_file() and p.suffix in ('.html', '.css', '.js')]
    for folder in ('assets', 'data'):
        sources += [p for p in (UI / folder).rglob('*') if p.is_file()
                    and p.suffix in ('.js', '.svg', '.png', '.jpg', '.webp', '.json', '.csv', '.xlsx')
                    and p.name != 'simulation-stubs.js']
    copied = []
    for source in sorted(sources):
        relative = source.relative_to(UI)
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        copied.append(relative.as_posix())
    (output / MARKER).write_text(json.dumps(copied, indent=2) + '\n', encoding='utf-8')
    if not (output / 'index.html').is_file():
        raise ValueError('UI/index.html is required for the homepage.')
    return copied


if __name__ == '__main__':
    files = build()
    print(f'Prepared {len(files)} static files in public/. API and stubs remain at the repository root.')
