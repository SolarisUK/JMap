"""Generate the offline/API bundle from actual deterministic simulator episodes.

Run using this script's absolute path from any directory. Agents explicitly replay
the optimiser while no trained policy exists. Forecast ranges are labelled naive.
"""
from __future__ import annotations
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import schemas as S
from simulation_service import SimulationService


def main():
    service = SimulationService()
    bundle = service.bundle()
    output = ROOT / "stubs"
    output.mkdir(exist_ok=True)

    def write(name, payload):
        path = output / f"{name}.json"
        path.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":"), allow_nan=False) + "\n", encoding="utf-8")
        return path

    for key in ("reference", "zones", "edges", "scenarios"):
        write(key, bundle[key])
    scenario = S.SCENARIOS[0]
    write("state_calm", service.state(scenario, "optimiser", 10))
    write("state_incident", service.state(scenario, "optimiser", 38))
    write("state_series", bundle["series"][scenario]["optimiser"])
    write("compare", bundle["compare"])
    for name in S.SCENARIOS:
        write(f"compare_{name}", bundle["compare"][name])
        for strategy in S.STRATEGIES:
            write(f"series_{name}_{strategy}", bundle["series"][name][strategy])
            write(f"states_{name}_{strategy}", bundle["states"][name][strategy])
    for zone in S.ZONE_ORDER:
        write(f"forecast_{zone}", bundle["forecasts"][zone])
    write("incident_response", {"ok": True, "incident_id": "inc_example", "incident": S.Incident("line_trip", S.B6_EDGE, 34, 14, 1.0).to_dict(), "scenario": scenario, "revision": 1})
    path = write("bundle", bundle)
    js = ROOT / "UI" / "assets" / "simulation-stubs.js"
    js.write_text("/* Generated by scripts/make_api_stubs.py from GridEnv. Synthetic data; model placeholders are explicit. */\nwindow.JMAP_SIMULATION_STUBS=" + json.dumps(bundle, ensure_ascii=False, separators=(",", ":"), allow_nan=False) + ";\n", encoding="utf-8")
    print(f"Generated {len(S.SCENARIOS)} scenarios x {len(S.STRATEGIES)} strategies x {S.STEPS_PER_EPISODE} complete states.")
    print(f"Bundle: {path} ({path.stat().st_size:,} bytes)")
    print(f"Browser fallback: {js}")
    print("Agents are not trained; their replay duplicates the optimiser. Forecast intervals are illustrative.")


if __name__ == "__main__":
    main()
