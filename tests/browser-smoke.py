"""Optional integrated dashboard checks: python tests/browser-smoke.py."""
import csv
import io
import json
import tempfile
from pathlib import Path
from playwright.sync_api import sync_playwright


def check(condition, message):
    if not condition:
        raise AssertionError(message)


with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1440, "height": 900})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto((Path(__file__).resolve().parents[1] / 'UI/explorer.html').as_uri())
    page.wait_for_selector('.map-region')
    check(page.locator('#geography-level').input_value() == 'local', 'Local resolution is the default')
    check(page.locator('.map-region').count() == 361, '361 actual district polygons load')
    check(page.locator('.regional-ranking-row').count() == 361, 'Every district is inspectable')
    check('350 values' in page.locator('#results-label').inner_text(), 'Missing NI consumption remains explicit')
    check(page.locator('.map-region-label:visible').count() == 0, 'No hundreds of overlapping labels')
    check(page.evaluate('document.documentElement.scrollHeight <= window.innerHeight'), 'Desktop dashboard fits one screen')
    check(page.locator('#map-stage').bounding_box()['height'] >= 400, 'Map keeps useful vertical space')
    check('246.4 TWh' == page.locator('#kpi-value-1').inner_text(), 'Mapped use matches actual dataset')
    check('61.6 GW' == page.locator('#kpi-value-3').inner_text(), 'Capacity has compact, correct units')
    screenshot_dir = Path(tempfile.gettempdir()) / 'jmap-dashboard-review'
    screenshot_dir.mkdir(exist_ok=True)
    page.screenshot(path=str(screenshot_dir / 'dashboard-1440.png'))

    page.fill('#area-search', 'Westminster')
    check(page.locator('.regional-ranking-row').count() == 1, 'Search filters area ranking')
    page.locator('.regional-ranking-row').click()
    check(page.locator('#regional-detail-title').inner_text() == 'Westminster', 'Selected area has exact detail')
    check('Westminster' in page.locator('#dashboard-scope').inner_text(), 'KPIs identify selected area')
    check(page.locator('.map-region-label:visible').count() == 1, 'Only selected area is labelled')
    page.evaluate('window.__pathBefore = document.querySelector(".map-region")')
    page.click('[data-heat-metric="perMeter"]')
    check('MWh / meter' in page.locator('#legend-title').inner_text(), 'Household intensity has correct units')
    check(page.evaluate('window.__pathBefore === document.querySelector(".map-region")'), 'Changing measure reuses projected paths')
    page.click('#zoom-regional-selection')
    check(float(page.locator('#zoom-label').inner_text().split('×')[0]) > 8, 'Small boroughs can be inspected at local scale')
    with page.expect_download() as event:
        page.click('#export-map')
    rows = list(csv.reader(io.StringIO(Path(event.value.path()).read_text(encoding='utf-8-sig'))))
    heading = next(i for i, row in enumerate(rows) if row and row[0] == 'ONS code')
    check(len(rows[heading + 1:]) == 1 and rows[heading + 1][1] == 'Westminster', 'CSV follows area search with source values')
    page.reload()
    check(page.locator('#area-search').input_value() == 'Westminster', 'Search restores from URL')
    check(page.locator('[data-heat-metric="perMeter"]').get_attribute('aria-pressed') == 'true', 'Local measure restores from URL')
    check(page.locator('#regional-detail-title').inner_text() == 'Westminster', 'Area selection restores from URL')
    page.fill('#area-search', 'Hartlepool')
    page.locator('.regional-ranking-row').click()
    check(page.locator('#kpi-value-1').inner_text() == '396.8 GWh', 'Smaller-area energy retains useful precision and units')
    page.fill('#area-search', '')
    page.select_option('#local-nation', 'northern-ireland')
    check(page.locator('.regional-ranking-row').count() == 11, 'NI districts remain inspectable')
    check(page.locator('#kpi-value-1').inner_text() == '—', 'No fabricated NI use total')
    check(page.locator('.regional-ranking-row small').all_inner_texts() == ['No data'] * 11, 'Unknown values are not zero')
    page.click('[data-heat-metric="capacity"]')
    check('11 values' in page.locator('#results-label').inner_text(), 'NI renewable capacity is separately available')
    page.fill('#area-search', 'no-such-authority')
    check('No matching areas' in page.locator('#regional-ranking').inner_text(), 'Empty area search is understandable')
    page.fill('#area-search', '')
    page.select_option('#local-nation', 'all')
    page.click('[data-heat-metric="renewable"]')
    check('40 values' in page.locator('#results-label').inner_text(), 'Suppressed renewable output stays unknown')

    page.select_option('#geography-level', 'nations')
    check(page.locator('.map-region').count() == 4, 'National balance remains available')
    check('21.5% deficit' in page.locator('[data-label-for-region="england"]').text_content(), 'Balance label matches sourced national data')
    page.locator('[data-ranking-nation="scotland"]').click()
    check('54 TWh' == page.locator('#kpi-value-1').inner_text(), 'National KPI reflects selected nation')
    original_colour = page.locator('.map-region[data-region-key="scotland"]').get_attribute('fill')
    page.click('#open-balance')
    check(page.locator('#balance-dialog').is_visible(), 'Detailed balance is on demand')
    page.select_option('#balance-sort', 'deficit')
    with page.expect_download() as event:
        page.click('#export-balance')
    rows = list(csv.reader(io.StringIO(Path(event.value.path()).read_text(encoding='utf-8-sig'))))
    heading = next(i for i, row in enumerate(rows) if row and row[0] == 'Nation')
    check(rows[heading + 1][0] == 'England', 'Annual export preserves selected ranking')
    check(abs(float(rows[heading + 1][4]) + 57.04046984948886) < 1e-6, 'Annual deficit matches net imports')
    page.locator('.scenario-controls summary').click()
    page.locator('#demand-change').focus()
    page.keyboard.press('End')
    page.locator('#generation-change').focus()
    page.keyboard.press('End')
    check(page.locator('#balance-rows .balance-status').all_inner_texts() == ['Annual deficit'] * 4, 'Annual scenario recomputes deficits')
    page.click('#close-balance')
    check('deficit' in page.locator('[data-label-for-region="scotland"]').text_content(), 'Scenario changes the nation map')
    check(page.locator('.map-region[data-region-key="scotland"]').get_attribute('fill') != original_colour, 'Scenario colour uses unchanged scale')
    page.click('[data-heat-metric="renewable"]')
    check('72.3% renewable' in page.locator('[data-label-for-region="scotland"]').text_content(), 'Renewable mix retains measured baseline')
    check('54 TWh' == page.locator('#kpi-value-1').inner_text(), 'Renewable baseline details do not show scenario energy')
    page.click('#open-balance')
    page.click('#reset-scenario')
    page.click('#close-balance')

    check(page.locator('[data-layer="sites"]').is_visible(), 'Layer controls remain visible after closing scenario dialog')
    page.click('[data-layer="sites"]')
    check(page.locator('#site-search').is_visible(), 'Sample site explorer remains available')
    page.fill('#site-search', 'Beatrice')
    check(page.locator('#results-label').inner_text() == '1 of 45 sites', 'Site search still filters curated assets')
    check('Synthetic' in page.locator('#kpi-context-1').inner_text(), 'Sample figures stay clearly synthetic')
    page.click('#reset-filters')
    page.click('#list-view')
    check(page.locator('#directory-body tr').count() == 45, 'Site directory is preserved')
    page.click('#map-view')
    page.click('[data-layer="heatmap"]')
    page.select_option('#geography-level', 'local')
    page.select_option('#local-nation', 'all')
    page.click('#about-data')
    check('unallocated' in page.locator('#dialog-body').inner_text().lower(), 'Sources disclose unmatched consumption')
    check('Office for National Statistics' in page.locator('#dialog-body').inner_text(), 'ONS attribution is available')
    page.click('#dialog-done')
    for width, height in [(1440,900),(1366,768),(1024,768),(768,900),(390,844),(320,800)]:
        page.set_viewport_size({'width':width,'height':height})
        page.wait_for_timeout(120)
        check(page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), f'No horizontal overflow at {width}')
        if width > 850:
            check(page.evaluate('document.documentElement.scrollHeight <= window.innerHeight'), f'Desktop remains one screen at {width}')
    page.locator('#map-stage').scroll_into_view_if_needed()
    page.screenshot(path=str(screenshot_dir / 'dashboard-mobile.png'))
    check(not errors, 'No browser errors: ' + repr(errors))
    print(json.dumps({'result':'passed','checks':'361 districts, coverage, compact desktop, search, selection, local zoom, units, CSV, URL restore, missing values, national scenarios, sample explorer, responsive layout','screenshots':str(screenshot_dir)}))
    browser.close()
